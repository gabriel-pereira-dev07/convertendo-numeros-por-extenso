let Numero_entre_0_9 = Number(prompt("Digite um número entre 0 e 9 : "));
switch (Numero_entre_0_9) {
  case 0:
    alert("zero");
    break;

  case 1:
    alert("um");
    break;

  case 2:
    alert("dois");
    break;

  case 3:
    alert("três");
    break;

  case 4:
    alert("quatro");
    break;

  case 5:
    alert("cinco");
    break;

  case 6:
    alert("seis");
    break;

  case 7:
    alert("sete");
    break;

  case 8:
    alert("oito");
    break;

  case 9:
    alert("nove");
    break;
  default:
    alert("Número desconhecido");
}
